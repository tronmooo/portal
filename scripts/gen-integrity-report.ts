// Write docs/INTEGRITY_REPORT.md from the last integrity run.
//   npx tsx scripts/gen-integrity-report.ts [--results <dir>] [--baseline <dir>] [--local <vitest.json>] [--checks <json>]
// --results   the run to report (default test-results/integrity)
// --baseline  an earlier run of the same scenarios (e.g. production before a fix);
//             a finding in the baseline that is absent from the run is listed as fixed
// --local     vitest's JSON report of the local suite
// --checks    {name, ok, seconds, tail}[] from running the existing live checks
import fs from "fs";
import path from "path";
import { ROOT } from "./workflow-inventory";
import { buildMatrix, stateOf } from "./gen-integrity-map";
import { KNOWN } from "../tests/integrity/known";
import type { ScenarioResult, Finding } from "../tests/integrity/framework";

const arg = (n: string) => { const i = process.argv.indexOf(n); return i >= 0 ? process.argv[i + 1] : undefined; };
interface Run { seed: number; at: string; target?: string; sha?: string; results: ScenarioResult[]; findings: Finding[]; timings: Array<{ call: string; ms: number }> }
const load = (dir?: string): Run | null => {
  if (!dir) return null;
  const f = path.join(path.resolve(dir), "results.json");
  return fs.existsSync(f) ? JSON.parse(fs.readFileSync(f, "utf8")) : null;
};

const run = load(arg("--results") ?? "test-results/integrity");
if (!run) { console.error("no results.json — run `npx tsx tests/integrity/run.ts` first"); process.exit(1); }
const baseline = load(arg("--baseline"));
const local = arg("--local") && fs.existsSync(arg("--local")!) ? JSON.parse(fs.readFileSync(arg("--local")!, "utf8")) : null;
const checks: Array<{ name: string; ok: boolean; seconds: number; tail: string }> | null = arg("--checks") && fs.existsSync(arg("--checks")!) ? JSON.parse(fs.readFileSync(arg("--checks")!, "utf8")) : null;

const L: string[] = [];
const out = (s = "") => L.push(s);
const by = (r: Run, s: string) => r.results.filter((x) => x.status === s);
const esc = (s: string) => s.replace(/\|/g, "\\|").replace(/\n/g, " ");
const { rows, scenarios } = buildMatrix();

out("# Integrity report");
out();
out("Generated by `npx tsx scripts/gen-integrity-report.ts` from the last integrity run — do not edit by hand.");
out("How the run works: `tests/integrity/README.md`. What depends on what, and the coverage matrix: `docs/INTEGRITY_MAP.md`.");
out();
out("**The rule this report is built on:** a scenario passes only when the action, the row read straight from the");
out("database, the figures computed from it (checked against an independent calculation) and — where it has a");
out("screen — a real browser all agree. A scenario that only saw a success answer is INCOMPLETE, not PASS.");
out();

// ── summary ─────────────────────────────────────────────────────────────────
const checksOf = (r: Run) => r.results.flatMap((x) => x.checks);
out("## Summary");
out();
out(`| | ${baseline ? `Before (${baseline.target ?? "production"}${baseline.sha ? ` @ ${baseline.sha}` : ""}) | ` : ""}This run (${run.target ?? "deployed app"}${run.sha ? ` @ ${run.sha}` : ""}) |`);
out(`|---|${baseline ? "---:|" : ""}---:|`);
const line = (label: string, f: (r: Run) => string | number) => out(`| ${label} | ${baseline ? `${f(baseline)} | ` : ""}${f(run)} |`);
line("Scenarios passed", (r) => by(r, "pass").length);
line("Scenarios failed", (r) => by(r, "fail").length + by(r, "error").length);
line("Scenarios incomplete (owed evidence)", (r) => by(r, "incomplete").length);
line("Scenarios skipped", (r) => by(r, "skipped").length);
line("Checks made", (r) => checksOf(r).length);
line("…of the action", (r) => checksOf(r).filter((c) => c.kind === "action").length);
line("…of database rows", (r) => checksOf(r).filter((c) => c.kind === "db").length);
line("…of dependent figures (vs the oracle)", (r) => checksOf(r).filter((c) => c.kind === "derived").length);
line("…in a browser (desktop + phone)", (r) => checksOf(r).filter((c) => c.kind === "screen").length);
line("…of account isolation", (r) => checksOf(r).filter((c) => c.kind === "isolation").length);
line("Checks failed", (r) => checksOf(r).filter((c) => !c.ok).length);
line("Random seed", (r) => r.seed);
line("Run at", (r) => r.at.slice(0, 16).replace("T", " ") + " UTC");
out();
if (local) {
  out(`**Local suite** (\`npx vitest run\`, runs on every push and pull request): ${local.numPassedTests} of ${local.numTotalTests} tests passed in ${local.testResults?.length ?? "?"} files${local.numFailedTests ? `, **${local.numFailedTests} failed**` : ""}. It includes the randomized oracle properties (\`tests/integrity-oracle-properties.test.ts\`), the model guard (\`tests/integrity-model.test.ts\`) and the guards for the fixes below.`);
  out();
}
if (checks) {
  const bad = checks.filter((c) => !c.ok);
  out(`**Existing live checks** (\`tests/live-*-check.ts\`, ${checks.length} run against the deployed app): ${checks.length - bad.length} passed${bad.length ? `, **${bad.length} failed**: ${bad.map((c) => `\`${c.name}\``).join(", ")}` : ""}.`);
  out();
}

// ── fixed ───────────────────────────────────────────────────────────────────
if (baseline) {
  const now = new Set(run.findings.map((f) => f.title));
  const fixed = baseline.findings.filter((f) => !now.has(f.title) && f.severity !== "gap");
  const stillFailing = new Set([...by(run, "fail"), ...by(run, "error")].map((r) => r.id));
  const wereFailing = [...by(baseline, "fail"), ...by(baseline, "error")].filter((r) => !stillFailing.has(r.id));
  out("## Found by the run, then fixed");
  out();
  out("Each was reproduced on production by the scenario named, root-caused, fixed, guarded by a local test that fails on the old code (`tests/integrity-run-fixes-2026-11-27.test.ts`) and rerun against the fixed deployment.");
  out();
  out("| Finding | Scenario | Before | Now |");
  out("|---|---|---|---|");
  const seen = new Set<string>();
  for (const f of fixed) {
    if (seen.has(f.title)) continue; seen.add(f.title);
    const r = run.results.find((x) => x.id === f.scenario);
    out(`| ${esc(f.title)}<br><sub>${esc(f.detail.slice(0, 260))}</sub> | \`${f.scenario}\` | failed | ${r?.status === "pass" ? "**pass**" : r?.status ?? "not rerun"} |`);
  }
  out();
  if (wereFailing.length) { out(`Scenarios that failed before and pass now: ${wereFailing.map((r) => `\`${r.id}\``).join(", ")}.`); out(); }
}

// ── failures ────────────────────────────────────────────────────────────────
const failing = [...by(run, "fail"), ...by(run, "error"), ...by(run, "incomplete")];
out(`## Failed scenarios (${failing.length})`);
out();
if (!failing.length) out("None.");
for (const r of failing) {
  out(`### ${r.status.toUpperCase()} — \`${r.id}\` ${r.title}`);
  out();
  for (const c of r.checks.filter((c) => !c.ok)) out(`- ✗ **[${c.kind}]** ${esc(c.what)}${c.detail ? ` — got: \`${esc(c.detail.slice(0, 300))}\`` : ""}`);
  if (r.error) out(`- error: \`${esc(r.error.split("\n")[0].slice(0, 300))}\``);
  if (r.missing.length) out(`- owes evidence it did not produce: ${r.missing.join(", ")}`);
  out();
  out("<details><summary>Steps to reproduce</summary>");
  out();
  out("```");
  for (const s of r.steps.slice(0, 60)) out(s.slice(0, 400));
  if (r.steps.length > 60) out(`… ${r.steps.length - 60} more steps in results.json`);
  out("```");
  out(`Rerun: \`npx tsx tests/integrity/run.ts --only '^${r.id.replace(/\./g, "\\.")}$' --seed ${run.seed}\``);
  out("</details>");
  out();
  for (const shot of r.screenshots) out(`![${r.id}](${path.relative("docs", shot)})`);
  if (r.screenshots.length) out();
}

// ── findings by kind ────────────────────────────────────────────────────────
const group = (sev: Finding["severity"][], title: string, extra: typeof KNOWN = []) => {
  const fs_ = run.findings.filter((f) => sev.includes(f.severity));
  out(`## ${title} (${fs_.length + extra.length})`);
  out();
  if (!fs_.length && !extra.length) { out("None found."); out(); return; }
  const seen = new Set<string>();
  for (const f of fs_) { if (seen.has(f.title)) continue; seen.add(f.title); out(`- **${esc(f.title)}** — ${esc(f.detail)} _(${f.scenario})_`); }
  for (const k of extra) out(`- **${k.title}** _(known${k.kind === "question" ? ", open question for the owner" : ""})_ — ${k.detail} Seen in: ${k.evidence}.`);
  out();
};
group(["bug"], "Bugs open in this run");
group(["discrepancy"], "Calculation discrepancies", KNOWN.filter((k) => k.kind === "discrepancy"));
group(["sync"], "Synchronization problems", KNOWN.filter((k) => k.kind === "sync"));

// ── performance ─────────────────────────────────────────────────────────────
out("## Performance");
out();
const byCall = new Map<string, number[]>();
for (const t of run.timings) byCall.set(t.call, [...(byCall.get(t.call) ?? []), t.ms]);
const stat = [...byCall.entries()].map(([call, ms]) => { const s = [...ms].sort((a, b) => a - b); return { call, n: ms.length, p50: s[Math.floor(s.length / 2)], max: s[s.length - 1] }; });
const slow = stat.filter((s) => s.max > 1500 && !/\/chat$/.test(s.call)).sort((a, b) => b.max - a.max);
out(`${run.timings.length} API calls timed (the request itself; time waiting out the write limit is not counted). Budget: 1.5 s.`);
out();
if (slow.length) {
  out("| Call | Calls | Median | Worst |");
  out("|---|---:|---:|---:|");
  for (const s of slow.slice(0, 15)) out(`| \`${s.call}\` | ${s.n} | ${s.p50} ms | **${s.max} ms** |`);
} else out("No call over 1.5 s.");
out();
const chat = stat.find((s) => /POST \/chat$/.test(s.call));
if (chat) { out(`AI Chat turns: ${chat.n}, median ${(chat.p50 / 1000).toFixed(1)} s, worst ${(chat.max / 1000).toFixed(1)} s (a model call; judged by what it stored, not by this).`); out(); }
const screens = run.results.find((r) => r.id === "browser.screens");
if (screens && screens.steps.length) {
  const rowsS = screens.steps.map((s) => /^\[(desktop|phone)\] (\S+): shown in (\d+) ms, settled in (\d+) ms/.exec(s)).filter(Boolean) as RegExpExecArray[];
  const routes = [...new Set(rowsS.map((m) => m[2]))];
  out("Screens (time from navigating to the screen being on the page, then to the network going quiet):");
  out();
  out("| Screen | Desktop shown | Desktop settled | Phone shown | Phone settled |");
  out("|---|---:|---:|---:|---:|");
  for (const route of routes) {
    const d = rowsS.find((m) => m[1] === "desktop" && m[2] === route), p = rowsS.find((m) => m[1] === "phone" && m[2] === route);
    out(`| \`${route}\` | ${d ? `${d[3]} ms` : "—"} | ${d ? `${d[4]} ms` : "—"} | ${p ? `${p[3]} ms` : "—"} | ${p ? `${p[4]} ms` : "—"} |`);
  }
  out();
}
const perfFindings = run.findings.filter((f) => f.severity === "perf");
for (const f of perfFindings) out(`- **${f.title}** — ${f.detail}`);
if (perfFindings.length) out();

// ── passed ──────────────────────────────────────────────────────────────────
out(`## Passed scenarios (${by(run, "pass").length})`);
out();
out("| Scenario | Area | Checks (action / database / derived / screen / isolation) | Time |");
out("|---|---|---|---:|");
for (const r of by(run, "pass")) {
  const n = (k: string) => r.checks.filter((c) => c.kind === k).length;
  out(`| \`${r.id}\` — ${esc(r.title)} | ${r.area} | ${n("action")} / ${n("db")} / ${n("derived")} / ${n("screen")} / ${n("isolation")} | ${(r.ms / 1000).toFixed(0)} s |`);
}
out();
const skipped = by(run, "skipped");
if (skipped.length) { out(`Skipped: ${skipped.map((r) => `\`${r.id}\` (${r.skippedWhy})`).join(", ")}.`); out(); }
if (checks) {
  out("### Existing live checks");
  out();
  out("| Check | Result | Time |");
  out("|---|---|---:|");
  for (const c of checks) out(`| \`${c.name}\` | ${c.ok ? "pass" : `**FAIL** — ${esc(c.tail.slice(0, 200))}`} | ${c.seconds} s |`);
  out();
}

// ── untested ────────────────────────────────────────────────────────────────
out("## Untested workflows and remaining coverage gaps");
out();
const noTest = rows.flatMap((r) => (["api", "chat"] as const).filter((d) => stateOf(r[d]) === "untested").map((d) => `${r.label} · ${r.op} · ${d === "api" ? "API" : "AI Chat"} (${r[d].doors.map((x) => `\`${x}\``).join(", ")})`));
const named = rows.flatMap((r) => (["api", "chat"] as const).filter((d) => stateOf(r[d]) === "tested").map((d) => `${r.label} · ${r.op} · ${d === "api" ? "API" : "Chat"}`));
const ui = rows.filter((r) => r.ui.doors.length && !r.ui.verifiedBy.length);
const verified = rows.flatMap((r) => (["ui", "api", "chat"] as const).filter((d) => stateOf(r[d]) === "verified")).length;
out(`Of the doors in the coverage matrix, **${verified}** are verified by an integrity scenario.`);
out();
out(`**No test of any kind (${noTest.length}):**`);
out();
for (const g of noTest) out(`- ${g}`);
out();
out(`**Named by an existing test, but not verified against the database by a scenario (${named.length}):** ${named.join("; ")}.`);
out();
out(`**Offered by a screen, but not driven by an integrity browser scenario (${ui.length}):** the browser scenarios drive the task and expense forms, a save while offline, a record made on another device, and every main screen on desktop and phone. Every other form is exercised by the per-screen live browser checks in \`docs/WORKFLOW_MATRIX.md\`, which assert what the screen shows but not the stored row.`);
out();
out("**Not covered by the integrity run at all:**");
out();
for (const g of [
  "Connected bank accounts (the provider session, sync, webhook) — needs a bank sandbox; only statement import is exercised, by `tests/live-finance-workflows-check.ts`.",
  "Uploading a real file and the AI extraction that follows (`/api/upload`, re-extract, Smart Fill) — the run creates documents with a 1×1 image and typed fields.",
  "The valuation engine's live web research and the lifecycle AI call — the run checks the engine's arithmetic on stored and typical figures, not the model's choice of assumptions.",
  "Workspace AI (document assist / review, notes and journal assistants, the reflection coach and its memory) — covered by `tests/live-workspace-ai-check.ts` and `tests/live-workspace-apps-check.ts`.",
  "Sign-up, password reset, account deletion and data export / import — never run against the shared smoke account by this suite.",
  "Chat variations beyond the commands in `tests/integrity/scenarios/chat.ts` — phrasing coverage is `tests/live-chat-variations-check.ts` and `tests/live-input-variations*-check.ts`.",
  "Load: the run is one user. The 60-writes-a-minute limit on the account is respected, not tested.",
  "The native iOS shell (Capacitor): the phone surface is a 390 px touch browser.",
]) out(`- ${g}`);
out();
out("### Known limits and open questions");
out();
for (const k of KNOWN.filter((k) => k.kind === "gap" || k.kind === "question")) out(`- **${k.title}**${k.kind === "question" ? " _(open question for the owner)_" : ""} — ${k.detail} Seen in: ${k.evidence}.`);
out();
const gapFindings = run.findings.filter((f) => f.severity === "gap");
for (const f of gapFindings) out(`- **${f.title}** — ${f.detail} _(${f.scenario})_`);
if (gapFindings.length) out();
void scenarios;

const file = path.join(ROOT, "docs/INTEGRITY_REPORT.md");
fs.writeFileSync(file, L.join("\n") + "\n");
console.log(`wrote ${path.relative(ROOT, file)}`);
