// Regenerate docs/WORKFLOW_MATRIX.md: every API route, chat tool and screen,
// grouped by domain, with the tests that reference each and the gaps.
//   npx tsx scripts/gen-workflow-matrix.ts
// The reading is in scripts/workflow-inventory.ts; tests/workflow-matrix.test.ts
// fails when a new route or tool has no domain.
import fs from "fs";
import path from "path";
import { TOOL_DEFINITIONS } from "../server/ai-engine";
import { DOMAINS, ROOT, buildInventory, type Coverage, type RouteRow, type ToolRow } from "./workflow-inventory";

const inv = buildInventory(TOOL_DEFINITIONS.map((t: any) => t.name));
const SYSTEM = "System (not a user workflow)";

const none = (c: Coverage) => !c.local.length && !c.contract.length && !c.live.length;
const deployed = (c: Coverage) => c.contract.length + c.live.length > 0;
const mark = (ok: boolean) => (ok ? "yes" : "**no**");

const userRoutes = inv.routes.filter((r) => r.domain !== SYSTEM);
const writes = userRoutes.filter((r) => r.write);
const reads = userRoutes.filter((r) => !r.write);
const writeTools = inv.tools.filter((t) => t.write);

// A screen is one page component, whatever aliases route to it.
const pages = new Map<string, { paths: string[]; desktop: Set<string>; touch: Set<string>; dom: Set<string> }>();
for (const s of inv.screens) {
  const p = pages.get(s.component) ?? { paths: [], desktop: new Set(), touch: new Set(), dom: new Set() };
  p.paths.push(s.path);
  s.desktop.forEach((f) => p.desktop.add(f));
  s.touch.forEach((f) => p.touch.add(f));
  s.dom.forEach((f) => p.dom.add(f));
  pages.set(s.component, p);
}

const L: string[] = [];
const out = (s = "") => L.push(s);

out("# Workflow matrix");
out();
out("Generated by `npx tsx scripts/gen-workflow-matrix.ts` — do not edit by hand.");
out("Every door into the app (API route, chat tool, screen) and the tests that");
out("reference it. A reference is evidence, not proof; a door NO test references");
out("is certainly unproven. Method: `scripts/workflow-inventory.ts`.");
out();
out("## Summary");
out();
out("| | Total | No test at all | Not exercised on the deployed app |");
out("|---|---:|---:|---:|");
out(`| API write routes | ${writes.length} | ${writes.filter((r) => none(r.tests)).length} | ${writes.filter((r) => !deployed(r.tests)).length} |`);
out(`| API read routes | ${reads.length} | ${reads.filter((r) => none(r.tests)).length} | ${reads.filter((r) => !deployed(r.tests)).length} |`);
out(`| Chat tools that write | ${writeTools.length} | ${writeTools.filter((t) => none(t.tests)).length} | ${writeTools.filter((t) => !deployed(t.tests)).length} |`);
out(`| Chat tools that read | ${inv.tools.length - writeTools.length} | ${inv.tools.filter((t) => !t.write && none(t.tests)).length} | ${inv.tools.filter((t) => !t.write && !deployed(t.tests)).length} |`);
out();
const pageList = [...pages.entries()];
out(`Screens: ${pageList.length} pages (${inv.screens.length} routes). ` +
  `${pageList.filter(([, p]) => !p.desktop.size && !p.touch.size).length} are opened by no live browser check, ` +
  `${pageList.filter(([, p]) => !p.touch.size).length} by none in a touch (phone) context.`);
out(`Write routes no screen calls: ${writes.filter((r) => !r.ui.length).length} (chat-only, script-only or dead).`);
out(`Test files read: ${inv.testFileCount}. Test files no config runs: ${inv.unlisted.length}` +
  (inv.unlisted.length ? ` (${inv.unlisted.map((f) => `\`${f}\``).join(", ")}).` : "."));
out();
out("## By domain");
out();
out("| Domain | Write routes | …untested | …not on deployed | Read routes | Chat tools | …write tools not on deployed |");
out("|---|---:|---:|---:|---:|---:|---:|");
for (const d of DOMAINS) {
  const rs = inv.routes.filter((r) => r.domain === d);
  const ts = inv.tools.filter((t) => t.domain === d);
  const w = rs.filter((r) => r.write);
  out(`| ${d} | ${w.length} | ${w.filter((r) => none(r.tests)).length} | ${w.filter((r) => !deployed(r.tests)).length} | ${rs.length - w.length} | ${ts.length} | ${ts.filter((t) => t.write && !deployed(t.tests)).length} |`);
}
out();
out("## Screens");
out();
out("Opened by a live browser check (found by the `#/route` it visits; a screen");
out("reached only by clicking through is not detected).");
out();
out("| Page | Routes | Desktop browser | Touch browser | jsdom tests |");
out("|---|---|---:|---:|---:|");
for (const [name, p] of pageList.sort((a, b) => a[0].localeCompare(b[0]))) {
  out(`| ${name} | ${p.paths.map((x) => `\`${x}\``).join(" ")} | ${p.desktop.size || "**0**"} | ${p.touch.size || "**0**"} | ${p.dom.size || "**0**"} |`);
}
out();

const routeLine = (r: RouteRow) =>
  `| \`${r.method} ${r.path}\` | ${mark(r.ui.length > 0)} | ${r.tests.local.length || "**0**"} | ${r.tests.contract.length + r.tests.live.length || "**0**"} |`;
const toolLine = (t: ToolRow) =>
  `| \`${t.name}\` | ${t.write ? "write" : "read"} | ${t.tests.local.length || "**0**"} | ${t.tests.contract.length + t.tests.live.length || "**0**"} |`;

out("## Every workflow door, by domain");
out();
out("Counts are test FILES that reference the door: local (`npx vitest run`) and");
out("deployed (contract suite, live scenarios, live checks, acceptance rig, audit scripts).");
for (const d of DOMAINS) {
  const rs = inv.routes.filter((r) => r.domain === d);
  const ts = inv.tools.filter((t) => t.domain === d);
  if (!rs.length && !ts.length) continue;
  out();
  out(`### ${d}`);
  if (rs.length) {
    out();
    out("| API route | A screen calls it | Local tests | Deployed tests |");
    out("|---|---|---:|---:|");
    rs.forEach((r) => out(routeLine(r)));
  }
  if (ts.length) {
    out();
    out("| Chat tool | Kind | Local tests | Deployed tests |");
    out("|---|---|---:|---:|");
    ts.forEach((t) => out(toolLine(t)));
  }
}
out();

fs.writeFileSync(path.join(ROOT, "docs/WORKFLOW_MATRIX.md"), L.join("\n"));
console.log(L.slice(6, 22).join("\n"));
console.log(`\nwrote docs/WORKFLOW_MATRIX.md (${L.length} lines)`);
